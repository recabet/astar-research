#!/usr/bin/env python3
"""Render the full result tables used in the report appendix."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
OUT = ROOT / "report" / "appendix_tables.tex"

FAMILIES = ["open", "random", "clustered", "rooms", "maze"]


def main() -> None:
    grid = pd.read_csv(RESULTS / "summary_grid_family_size.csv")
    grid["family"] = pd.Categorical(grid["family"], FAMILIES, ordered=True)
    grid = grid.sort_values(["family", "size"])

    weighted = pd.read_csv(RESULTS / "summary_weighted_by_family.csv")
    weighted = weighted[weighted["policy"] == "closed"]
    weighted["workload"] = pd.Categorical(
        weighted["workload"], FAMILIES + ["road"], ordered=True)
    weighted = weighted.sort_values(["workload", "epsilon"])

    lines = []
    lines.append("% Generated by scripts/render_appendix_tables.py\n")
    lines.append("\\clearpage\n\\onecolumn\n")
    lines.append("\\section*{Appendix A: Full grid results}\n")
    lines.append("\\begin{longtable}{lccc}\n")
    lines.append("\\caption{Grid medians by family and size.  Time ratio is "
                 "Dijkstra / A*; expansion ratio is Dijkstra / A*.}\\label{tab:appendix-grid}\\\\\n")
    lines.append("\\toprule\n")
    lines.append("family & size & time ratio & expansion ratio\\\\\n")
    lines.append("\\midrule\n\\endfirsthead\n")
    lines.append("\\toprule\n")
    lines.append("family & size & time ratio & expansion ratio\\\\\n")
    lines.append("\\midrule\n\\endhead\n")
    for _, row in grid.iterrows():
        lines.append(
            f"{row['family']} & {int(row['size'])} & "
            f"{row['time_ratio_median']:.2f} & {row['exp_ratio_median']:.2f}\\\\\n")
    lines.append("\\bottomrule\n\\end{longtable}\n\n")

    lines.append("\\section*{Appendix B: Full closed-list weighted sweep}\n")
    lines.append("\\begin{longtable}{llcc}\n")
    lines.append("\\caption{Closed-list weighted A* across all grid families and "
                 "the unit-hop road graph.  Cost ratio is returned path cost / "
                 "optimal cost.}\\label{tab:appendix-weighted}\\\\\n")
    lines.append("\\toprule\n")
    lines.append("workload & $\\epsilon$ & time ratio & cost ratio\\\\\n")
    lines.append("\\midrule\n\\endfirsthead\n")
    lines.append("\\toprule\n")
    lines.append("workload & $\\epsilon$ & time ratio & cost ratio\\\\\n")
    lines.append("\\midrule\n\\endhead\n")
    for _, row in weighted.iterrows():
        lines.append(
            f"{row['workload']} & {row['epsilon']:.2f} & "
            f"{row['time_ratio']:.2f} & {row['cost_ratio']:.3f}\\\\\n")
    lines.append("\\bottomrule\n\\end{longtable}\n\n\\twocolumn\n")

    OUT.write_text("".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
